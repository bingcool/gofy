// TestGenerateIsIdempotent: re-running the scaffold in a directory it already
// generated leaves the files alone instead of failing. Only --force rewrites.
// TestGenerateIsIdempotent：在已生成过的目录里重跑脚手架会保留文件而不是报错。只有
// --force 才重写。
func TestGenerateIsIdempotent(t *testing.T) {
	dir := filepath.Join(t.TempDir(), "demo")
	s := newTestScaffold("demo")
	if err := s.Generate(dir, false); err != nil {
		t.Fatalf("first Generate: %v", err)
	}
	edited := "package main\n\n// locally edited\n"
	if err := os.WriteFile(filepath.Join(dir, "main.go"), []byte(edited), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := s.Generate(dir, false); err != nil {
		t.Fatalf("second Generate: %v", err)
	}
	if got := readFile(t, filepath.Join(dir, "main.go")); got != edited {
		t.Errorf("re-run overwrote an edited file:\n%s", got)
	}
	if err := s.Generate(dir, true); err != nil {
		t.Fatalf("Generate with force: %v", err)
	}
	if got := readFile(t, filepath.Join(dir, "main.go")); got == edited {
		t.Error("--force did not rewrite the file")
	}
}

// TestGenerateForceKeepsGoModRequirements pins what --force may rewrite: the
// scaffold's own files, not the caller's module identity. A go.mod that already
// carries a go directive and extra requirements keeps both, and only gains the
// framework requirement and replace.
// TestGenerateForceKeepsGoModRequirements 固定 --force 可以重写的范围：脚手架自己的
// 文件，而不是调用方的模块身份。已有 go 指令与额外依赖的 go.mod 全部保留，只追加框架
// 依赖与 replace。
func TestGenerateForceKeepsGoModRequirements(t *testing.T) {
	dir := filepath.Join(t.TempDir(), "demo")
	if err := os.MkdirAll(dir, 0o755); err != nil {
		t.Fatal(err)
	}
	existing := "module example.com/demo\n\ngo 1.24\n\ntoolchain go1.24.3\n\nrequire github.com/google/uuid v1.6.0\n"
	if err := os.WriteFile(filepath.Join(dir, "go.mod"), []byte(existing), 0o644); err != nil {
		t.Fatal(err)
	}
	s := newTestScaffold("demo")
	s.GoVersion = "1.26"
	s.Replace = "/tmp/gofy"
	if err := s.Generate(dir, true); err != nil {
		t.Fatalf("Generate: %v", err)
	}
	goMod := readFile(t, filepath.Join(dir, "go.mod"))
	for _, want := range []string{
		"module example.com/demo",
		"go 1.24",
		"toolchain go1.24.3",
		"github.com/google/uuid v1.6.0",
		"github.com/bingcool/gofy",
		"replace github.com/bingcool/gofy => /tmp/gofy",
	} {
		if !strings.Contains(goMod, want) {
			t.Errorf("go.mod lost %q under --force:\n%s", want, goMod)
		}
	}
	if strings.Contains(goMod, "go 1.26") {
		t.Errorf("--force reset the go directive:\n%s", goMod)
	}
	// The rest of the scaffold is still regenerated.
	// 其余脚手架文件仍然照常重写。
	if main := readFile(t, filepath.Join(dir, "main.go")); !strings.Contains(main, "func main()") {
		t.Errorf("main.go was not generated:\n%s", main)
	}
}

// TestGenerateRefusesForeignDirectory: a directory with unrelated content is a
// mistake, and it is reported before anything is written.
// TestGenerateRefusesForeignDirectory：含无关内容的目录是误用，必须在写文件之前报错。
func TestGenerateRefusesForeignDirectory(t *testing.T) {
	dir := filepath.Join(t.TempDir(), "existing")
	if err := os.MkdirAll(dir, 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(dir, "README.md"), []byte("someone else's project"), 0o644); err != nil {
		t.Fatal(err)
	}
	s := newTestScaffold("existing")
	if err := s.Generate(dir, false); err == nil {
		t.Fatal("expected Generate to refuse a foreign directory")
	}
	if _, err := os.Stat(filepath.Join(dir, "main.go")); !os.IsNotExist(err) {
		t.Error("a file was written into the refused directory")
	}
	if err := s.Generate(dir, true); err != nil {
		t.Fatalf("Generate with force: %v", err)
	}
}

func TestOutputPath(t *testing.T) {
	cases := map[string]string{
		"main.go.tmpl":       "main.go",
		"app/config.go.tmpl": "app/config.go",
		"gitignore.tmpl":     ".gitignore",
		"dockerignore.tmpl":  ".dockerignore",
	}
	for in, want := range cases {
		got, ok := outputPath(in)
		if !ok || got != want {
			t.Errorf("outputPath(%q) = %q, %v; want %q, true", in, got, ok, want)
		}
	}
	if _, ok := outputPath("README.md"); ok {
		t.Error("outputPath must reject non-template files")
	}
}

func readFile(t *testing.T, path string) string {
	t.Helper()
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("read %s: %v", path, err)
	}
	return string(data)
}

