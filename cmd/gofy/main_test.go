package main

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

func newTestScaffold(name string) scaffold {
	return scaffold{
		Name:         name,
		EnvPrefix:    strings.ToUpper(strings.ReplaceAll(name, "-", "_")),
		Module:       "example.com/" + name,
		WithScripts:  true,
		WithMakefile: true,
		GoVersion:    "1.24",
	}
}

func TestGenerateDefaults(t *testing.T) {
	dir := filepath.Join(t.TempDir(), "demo")
	s := newTestScaffold("demo")
	if err := s.Generate(dir, false); err != nil {
		t.Fatalf("Generate: %v", err)
	}

	want := []string{
		"go.mod",
		"main.go",
		"config.yaml",
		".gitignore",
		"Makefile",
		"app/config/config.go",
		"app/module/example/module.go",
		"app/module/example/dto/example.go",
		"app/module/example/handler/example.go",
		"script/register.go",
		"script/example.go",
	}
	for _, name := range want {
		if _, err := os.Stat(filepath.Join(dir, name)); err != nil {
			t.Errorf("missing %s: %v", name, err)
		}
	}
	for _, name := range []string{"Dockerfile", ".dockerignore"} {
		if _, err := os.Stat(filepath.Join(dir, name)); !os.IsNotExist(err) {
			t.Errorf("%s should not be generated by default", name)
		}
	}

	goMod := readFile(t, filepath.Join(dir, "go.mod"))
	if !strings.Contains(goMod, "module example.com/demo") {
		t.Errorf("go.mod missing module path:\n%s", goMod)
	}
	if !strings.Contains(goMod, "github.com/bingcool/gofy v1.0.0") {
		t.Errorf("go.mod missing gofy requirement:\n%s", goMod)
	}

	config := readFile(t, filepath.Join(dir, "config.yaml"))
	if strings.Contains(config, "db:") || strings.Contains(config, "dsn") {
		t.Errorf("default config must not include database settings:\n%s", config)
	}

	main := readFile(t, filepath.Join(dir, "main.go"))
	if !strings.Contains(main, "DEMO_CONFIG") {
		t.Errorf("main.go missing app-specific config env var")
	}
	if strings.Contains(main, "WithDatabase") {
		t.Errorf("main.go must not wire a database by default")
	}
}

func TestGenerateWithDBAndDocker(t *testing.T) {
	dir := filepath.Join(t.TempDir(), "order-service")
	s := newTestScaffold("order-service")
	s.WithDB = true
	s.WithDocker = true
	if err := s.Generate(dir, false); err != nil {
		t.Fatalf("Generate: %v", err)
	}

	for _, name := range []string{"Dockerfile", ".dockerignore"} {
		if _, err := os.Stat(filepath.Join(dir, name)); err != nil {
			t.Errorf("missing %s: %v", name, err)
		}
	}
	config := readFile(t, filepath.Join(dir, "config.yaml"))
	if !strings.Contains(config, "dsn: ${DB_DSN}") {
		t.Errorf("config.yaml must reference DB_DSN instead of embedding a secret:\n%s", config)
	}
	if strings.Contains(config, "password") {
		t.Errorf("config.yaml must not contain credentials:\n%s", config)
	}
	main := readFile(t, filepath.Join(dir, "main.go"))
	if !strings.Contains(main, "ORDER_SERVICE_CONFIG") {
		t.Errorf("main.go missing ORDER_SERVICE_CONFIG")
	}
	if !strings.Contains(main, "gofy.WithDatabase(cfg.DB)") {
		t.Errorf("main.go missing database wiring:\n%s", main)
	}
	script := readFile(t, filepath.Join(dir, "script/example.go"))
	if !strings.Contains(script, "rt.DB") {
		t.Errorf("database script missing rt.DB usage:\n%s", script)
	}
	dockerfile := readFile(t, filepath.Join(dir, "Dockerfile"))
	if !strings.Contains(dockerfile, "order-service") {
		t.Errorf("Dockerfile missing application name:\n%s", dockerfile)
	}
}

func TestGenerateWithoutScripts(t *testing.T) {
	dir := filepath.Join(t.TempDir(), "demo")
	s := newTestScaffold("demo")
	s.WithScripts = false
	if err := s.Generate(dir, false); err != nil {
		t.Fatalf("Generate: %v", err)
	}
	if _, err := os.Stat(filepath.Join(dir, "script")); !os.IsNotExist(err) {
		t.Errorf("script/ should not be generated when scripts are disabled")
	}
	main := readFile(t, filepath.Join(dir, "main.go"))
	if strings.Contains(main, "WithScripts") {
		t.Errorf("main.go must not register scripts when they are disabled")
	}
}

func TestGenerateRefusesNonEmptyDirectory(t *testing.T) {
	dir := filepath.Join(t.TempDir(), "demo")
	s := newTestScaffold("demo")
	if err := s.Generate(dir, false); err != nil {
		t.Fatalf("first Generate: %v", err)
	}
	if err := s.Generate(dir, false); err == nil {
		t.Fatal("expected Generate to refuse a non-empty directory")
	}
	if err := s.Generate(dir, true); err != nil {
		t.Fatalf("Generate with force: %v", err)
	}
}

func TestOutputPath(t *testing.T) {
	cases := map[string]string{
		"main.go.tmpl":       "main.go",
		"app/config.go.tmpl": "app/config.go",
		"gitignore.tmpl":     ".gitignore",
		"dockerignore.tmpl":  ".dockerignore",
	}
	for in, want := range cases {
		got, ok := outputPath(in)
		if !ok || got != want {
			t.Errorf("outputPath(%q) = %q, %v; want %q, true", in, got, ok, want)
		}
	}
	if _, ok := outputPath("README.md"); ok {
		t.Error("outputPath must reject non-template files")
	}
}

func readFile(t *testing.T, path string) string {
	t.Helper()
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("read %s: %v", path, err)
	}
	return string(data)
}
