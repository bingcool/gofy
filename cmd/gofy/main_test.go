func TestGenerateDefaults(t *testing.T) {
	dir := filepath.Join(t.TempDir(), "demo")
	s := newTestScaffold("demo")
	if err := s.Generate(dir, false); err != nil {
		t.Fatalf("Generate: %v", err)
	}

	want := []string{
		"go.mod",
		// Entry layer: command classification, options, reload and the Nacos
		// watcher are separate files, matching the demo layout.
		// 入口层：命令分类、选项、热更新与 Nacos 监听各自成文件，与 demo 布局一致。
		"main.go",
		"config.go",
		"options.go",
		"reload.go",
		"fatal.go",
		"nacos_watch.go",
		"config.yaml",
		"application.yaml",
		"nacos.yaml",
		".gitignore",
		"Makefile",
		// app/ mirrors demo-service: config, appio, container, middleware and one
		// module with the full controller/service/repository/model split.
		// app/ 与 demo-service 同构：config、appio、container、middleware，以及一个
		// 带完整 controller/service/repository/model 分层的模块。
		"app/config/config.go",
		"app/config/log.go",
		"app/appio/io_runtime.go",
		"app/appio/db_module.go",
		"app/appio/snapshot.go",
		"app/appio/db/db.go",
		"app/container/container.go",
		"app/container/module_factories.go",
		"app/container/repository_declare.go",
		"app/container/service_declare.go",
		"app/middleware/registry.go",
		"app/middleware/auth.go",
		"app/middleware/audit.go",
		"app/module/example/module.go",
		"app/module/example/controller/example_controller.go",
		"app/module/example/dto/example.go",
		"app/module/example/innerapi/innerapi.go",
		"app/module/example/model/examplemodel/example_model.go",
		"app/module/example/repository/example_repository.go",
		"app/module/example/service/example_service.go",
		"app/module/example/service/dependencies.go",
		"script/register.go",
		"script/ping.go",
		"worker/register.go",
		"worker/worker.go",
		"worker/group1/abc_register.go",
		"worker/group1/heartbeat.go",
		"migrations/0001_example.sql",
		"shell/check-imports.sh",
	}
	for _, name := range want {
		if _, err := os.Stat(filepath.Join(dir, name)); err != nil {
			t.Errorf("missing %s: %v", name, err)
		}
	}
	for _, name := range []string{"Dockerfile", ".dockerignore", "internal"} {
		if _, err := os.Stat(filepath.Join(dir, name)); !os.IsNotExist(err) {
			t.Errorf("%s should not be generated by default", name)
		}
	}

	goMod := readFile(t, filepath.Join(dir, "go.mod"))
	if !strings.Contains(goMod, "module example.com/demo") {
		t.Errorf("go.mod missing module path:\n%s", goMod)
	}
	if !strings.Contains(goMod, "github.com/bingcool/gofy v1.0.0") {
		t.Errorf("go.mod missing gofy requirement:\n%s", goMod)
	}

	config := readFile(t, filepath.Join(dir, "config.yaml"))
	if strings.Contains(config, "db:") || strings.Contains(config, "dsn") {
		t.Errorf("default config must not include database settings:\n%s", config)
	}
	if !strings.Contains(config, "api_key: ${DEMO_API_KEY}") {
		t.Errorf("config.yaml must read the api key from the environment:\n%s", config)
	}

	entry := readFile(t, filepath.Join(dir, "config.go"))
	if !strings.Contains(entry, "DEMO_CONFIG") {
		t.Errorf("config.go missing app-specific config env var")
	}
	// The database wiring itself stays in both shapes: --with-db only decides
	// whether config.yaml carries an enabled db section, so a later `db:` block
	// needs no regeneration.
	// 数据库接线两种形态都保留：--with-db 只决定 config.yaml 是否带启用的 db 段，
	// 之后补一个 `db:` 段落不需要重新生成。
	options := readFile(t, filepath.Join(dir, "options.go"))
	if !strings.Contains(options, "gofy.WithWorkerGroups(groups...)") {
		t.Errorf("options.go must register the worker groups:\n%s", options)
	}
	if !strings.Contains(options, `gofy.WithAPIPrefix("/api/v1")`) {
		t.Errorf("options.go missing the shared API prefix:\n%s", options)
	}
	if !strings.Contains(readFile(t, filepath.Join(dir, "main.go")), "appOptions(") {
		t.Errorf("main.go must delegate wiring to appOptions")
	}

	// GOFY_ENV must be read once, before the config.yaml fallback writes it.
	// Re-reading after Setenv is always non-empty, which silently disables the
	// reload path that lets a config change drive the environment.
	// GOFY_ENV 只能读一次，且要在 config.yaml 回落写入它之前。Setenv 之后再读恒为非空，
	// 会让「配置变更驱动环境变量」的重载路径静默失效。
	mainSrc := readFile(t, filepath.Join(dir, "main.go"))
	if got := strings.Count(mainSrc, `os.Getenv("GOFY_ENV")`); got != 1 {
		t.Errorf("GOFY_ENV is read %d times, want exactly 1 (capture before Setenv):\n%s", got, mainSrc)
	}
	if !strings.Contains(mainSrc, "envFromProcess: envFromProcess,") {
		t.Errorf("reloader does not reuse the captured envFromProcess:\n%s", mainSrc)
	}
}

