func newTestScaffold(name string) scaffold {
	return scaffold{
		Name:         name,
		EnvPrefix:    strings.ToUpper(strings.ReplaceAll(name, "-", "_")),
		Module:       "example.com/" + name,
		WithScripts:  true,
		WithWorker:   true,
		WithMakefile: true,
		GoVersion:    "1.24",
	}
}

func TestGenerateDefaults(t *testing.T) {
	dir := filepath.Join(t.TempDir(), "demo")
	s := newTestScaffold("demo")
	if err := s.Generate(dir, false); err != nil {
		t.Fatalf("Generate: %v", err)
	}

	want := []string{
		"go.mod",
		"main.go",
		"config.yaml",
		".gitignore",
		"Makefile",
		"app/config/config.go",
		"app/module/example/module.go",
		"app/module/example/dto/example.go",
		"app/module/example/handler/example.go",
		"script/register.go",
		"script/example.go",
		"worker/register.go",
		"worker/example.go",
	}
	for _, name := range want {
		if _, err := os.Stat(filepath.Join(dir, name)); err != nil {
			t.Errorf("missing %s: %v", name, err)
		}
	}
	for _, name := range []string{"Dockerfile", ".dockerignore"} {
		if _, err := os.Stat(filepath.Join(dir, name)); !os.IsNotExist(err) {
			t.Errorf("%s should not be generated by default", name)
		}
	}

	goMod := readFile(t, filepath.Join(dir, "go.mod"))
	if !strings.Contains(goMod, "module example.com/demo") {
		t.Errorf("go.mod missing module path:\n%s", goMod)
	}
	if !strings.Contains(goMod, "github.com/bingcool/gofy v1.0.0") {
		t.Errorf("go.mod missing gofy requirement:\n%s", goMod)
	}

	config := readFile(t, filepath.Join(dir, "config.yaml"))
	if strings.Contains(config, "db:") || strings.Contains(config, "dsn") {
		t.Errorf("default config must not include database settings:\n%s", config)
	}

	main := readFile(t, filepath.Join(dir, "main.go"))
	if !strings.Contains(main, "DEMO_CONFIG") {
		t.Errorf("main.go missing app-specific config env var")
	}
	if strings.Contains(main, "WithDatabase") {
		t.Errorf("main.go must not wire a database by default")
	}
	if !strings.Contains(main, "gofy.WithWorkerGroups(workerGroups...)") {
		t.Errorf("main.go must register the worker groups:\n%s", main)
	}
}

